const parentSections = document.querySelector('.LibrarySections');
const totalPages = document.getElementById('page-num');
const sectionNmae = document.getElementById('section-name');
const bookTitle = document.getElementById('book-title');
const author = document.getElementById('book-author');
const pages = document.getElementById('book-pages');
const add = document.querySelector('.add-book-container button');

function displaySection( data ) {
    data.forEach( s => {
        const section = document.createElement('div');
        section.classList.add("section");
        section.innerHTML = `
                                <div class="header">
                                    <h2>كتب <span class="section-name">${s["section-name"]}</span></h2>
                                    <button class="fa-solid fa-chevron-up"></button>
                                </div>
                                <div class="books"></div>
                            `
        const books = section.querySelector('.books');
        displayBook(s["books"]).forEach(book => {
            books.appendChild(book);
        });
        parentSections.appendChild(section);
    });
}
displaySection( Library )

function displayBook( b ) {
    return b.map( b => {
        const book = document.createElement('div');
        book.classList.add('book');
        book.innerHTML = `
                            <h3 class="title">${b["title"]}</h3>
                            <p>المؤلف: <span class="author">${b["author"]}</span></p>
                            <p>الصفحات: <span class="pages">${b["pages"]}</span></p>
                        `
        return book
    });
}

parentSections.addEventListener( 'click', e => {
    if (e.target.classList.contains('fa-chevron-up')) {
        const section = e.target.closest('.section');
        const books = section.querySelector('.books');
        books.style.maxHeight = books.scrollHeight + 10 + 'px';
        books.style.setProperty('--books-height-', - (books.scrollHeight + 20) + 'px');
        if (section.classList.contains('disabled')) {
            books.style.maxHeight = books.scrollHeight + 10 + 'px';
            books.style.setProperty('--books-height-', - (books.scrollHeight + 100) + 'px');
            section.classList.toggle('disabled');
        } else {
            section.classList.toggle('disabled');
            books.style.maxHeight = 0 + 'px';
        }
    }
});

function pageNum( data ) {
    if ( Array.isArray( data ) ) {
        totalPages.textContent = Number(totalPages.textContent) + data.reduce((acc, curr, idx, arr) => {
            return curr["books"].reduce((acc, curr, idx, arr) => {
                return curr["pages"] + acc
            }, 0) + acc
        }, 0);
    } else {
        totalPages.textContent = Number(totalPages.textContent) + data["pages"]
    }
}
pageNum( Library )

add.addEventListener( 'click' , e => {
    e.preventDefault();
    const cleanedBookTitle = clean(bookTitle);
    const cleanedSectionName = clean(sectionNmae);
    const cleanedAuthorName = clean(author);
    const pagesNumber = Number( pages.value );
    for (let i = 0; i < Library.length; i++) {
        for (let j = 0; j < Library[i]["books"].length; j++) {
            if (Library[i]["books"][j]["title"] === cleanedBookTitle) {
                alert('This book already exists.');
                clearInputs();
                return
            }
        }
    }
    const newBook = {
        "title": cleanedBookTitle,
        "author": cleanedAuthorName,
        "pages": pagesNumber
    }
    for ( let i = 0 ; i < Library.length ; i++ ) {
        if ( Library[i]["section-name"] === cleanedSectionName ) {
            Library[i]["books"].push( newBook )
            pageNum( newBook )
            const span = [ ...document.querySelectorAll('.section-name') ].find ( ele => ele.textContent === cleanedSectionName );
            const books = span.closest('.section').querySelector('.books');
            books.appendChild( displayBook( [newBook] )[0] );
            alert(`Book added to the "${Library[i]["section-name"]}" section successfully.`);
            clearInputs();
            return
        }
    }
    const newSection = {
        "section-name": cleanedSectionName,
        "books": [
            newBook
        ]
    }
    Library.push( newSection )
    pageNum( [newSection] )
    displaySection ( [newSection] )
    alert(`New section "${newSection["section-name"]}" created, and the book was added successfully.`);
    clearInputs();
    return
});

function clearInputs() {
    bookTitle.value = '';
    sectionNmae.value = '';
    author.value = '';
    pages.value = '';
}

function clean( input ) {
    const dirtyInput = input.value.trim();
    const words = dirtyInput.split(' ');
    const cleanedInput = [];
    if ( dirtyInput.length > 0 ) {
        for ( let i = 0 ; i < words.length ; i++ ) {
            cleanedInput.push( words[i].slice( 0 , 1 ).toUpperCase() + words[i].slice( 1 , words[i].length ).toLowerCase() );
        }
    }
    return cleanedInput.join(' ');
}